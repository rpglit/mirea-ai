"""Built-in nets and task metadata for the PN catalog (MATERIALS_ANALYSIS 3.1).

Nets use the canonical JSON format (ARCH section 4.1). Tasks whose net is
not fully determined by the methodic carry a built-in model solution
(D-053): the report says so in ``notes`` and the user may override via
``spec["net"]``.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


def _net(
    places: list[str],
    transitions: list[str],
    inputs: dict[str, dict[str, int]],
    outputs: dict[str, dict[str, int]],
    marking: dict[str, int],
    **extra: Any,
) -> dict[str, Any]:
    return {
        "places": list(places),
        "transitions": list(transitions),
        "inputs": {t: dict(d) for t, d in inputs.items()},
        "outputs": {t: dict(d) for t, d in outputs.items()},
        "initial_marking": dict(marking),
        **extra,
    }


